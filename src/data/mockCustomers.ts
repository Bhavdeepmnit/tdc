/** Helper to reduce boilerplate while keeping each record fully typed. */
function make(
  id: string,
  partial: Omit<Customer, 'id' | 'matchmakerId' | 'isActive' | 'createdAt' | 'updatedAt'>,
): Customer {
  const isActive =
    partial.status !== CustomerStatus.CLOSED && partial.status !== CustomerStatus.ON_HOLD;
  return {
    id,
    matchmakerId: MATCHMAKER_ID,
    isActive,
    createdAt: '2026-01-15T09:00:00.000Z',
    updatedAt: '2026-05-30T09:00:00.000Z',
    ...partial,
  };
}

