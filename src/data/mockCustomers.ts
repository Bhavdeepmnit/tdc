/** Project a full Customer down to the dashboard/list summary shape. */
export function toSummary(c: Customer): CustomerSummary {
  return {
    id: c.id,
    fullName: c.fullName,
    gender: c.gender,
    age: getAge(c.dateOfBirth),
    currentCity: c.location.currentCity,
    profession: c.career.profession,
    avatarUrl: c.avatarUrl,
    status: c.status,
  };
}
